export const DICTS: Record<Lang, Dict> = { vi, en };

export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? DICTS.vi[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(`{${k}}`, String(v));
    }
  }
  return s;
}

export function fmtPrice(n: number): string {
  const abs = Math.abs(n);
  // dynamic precision so sub-cent pairs (PEPE, SHIB…) stay readable
  const max = abs >= 100 ? 2 : abs >= 1 ? 4 : abs >= 0.01 ? 5 : abs >= 0.0001 ? 6 : 8;
  return new Intl.NumberFormat("en-US", {
    minimumFractionDigits: 2,
    maximumFractionDigits: max,
  }).format(n);
}

/** "PEPEUSDT" → "PEPE" — base asset label for any pair chip. */
export function symbolLabel(sym: string): string {
  const base = sym.replace(/(USDT|USDC|FDUSD|TUSD|BUSD)$/i, "");
  return base || sym;
}

export function fmtPct(n: number): string {
  return `${n >= 0 ? "+" : ""}${n.toFixed(2)}%`;
}

export function fmtTime(t: number, lang: Lang): string {
  return new Date(t).toLocaleString(lang === "vi" ? "vi-VN" : "en-US", {
    day: "2-digit",
    month: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    hour12: false,
  });
}
